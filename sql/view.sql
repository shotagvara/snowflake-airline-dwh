CREATE OR REPLACE SECURE VIEW AIRLINE_DWH.MART.VW_FACT_AIRLINE_TRAVEL_SECURE AS
SELECT
    PASSENGER_ID,
    DEPARTURE_DATE,
    AIRPORT_NAME,
    AIRPORT_COUNTRY_CODE,
    ARRIVAL_AIRPORT,
    PILOT_NAME,
    FLIGHT_STATUS,
    TICKET_TYPE,
    PASSENGER_STATUS,
    PASSENGER_COUNT
FROM AIRLINE_DWH.MART.FACT_AIRLINE_TRAVEL;

SELECT COUNT(*) AS ROWS_IN_VIEW
FROM AIRLINE_DWH.MART.VW_FACT_AIRLINE_TRAVEL_SECURE;



# Создали политику 
CREATE OR REPLACE ROW ACCESS POLICY AIRLINE_DWH.MART.AIRLINE_COUNTRY_RAP
AS (AIRPORT_COUNTRY_CODE VARCHAR)
RETURNS BOOLEAN ->
    CASE
        WHEN CURRENT_ROLE() = 'ACCOUNTADMIN' THEN TRUE
        WHEN CURRENT_ROLE() = 'AIRLINE_US_ANALYST'
             AND AIRPORT_COUNTRY_CODE = 'US' THEN TRUE
        ELSE FALSE
    END;



# Прикрепили политику к столбцу
ALTER VIEW AIRLINE_DWH.MART.VW_FACT_AIRLINE_TRAVEL_SECURE
    ADD ROW ACCESS POLICY AIRLINE_DWH.MART.AIRLINE_COUNTRY_RAP
    ON (AIRPORT_COUNTRY_CODE);



#Создали роль аналитика и выдали ей права
CREATE ROLE IF NOT EXISTS AIRLINE_US_ANALYST;

GRANT USAGE ON WAREHOUSE AIRLINE_WH
    TO ROLE AIRLINE_US_ANALYST;

GRANT USAGE ON DATABASE AIRLINE_DWH
    TO ROLE AIRLINE_US_ANALYST;

GRANT USAGE ON SCHEMA AIRLINE_DWH.MART
    TO ROLE AIRLINE_US_ANALYST;

GRANT SELECT ON VIEW AIRLINE_DWH.MART.VW_FACT_AIRLINE_TRAVEL_SECURE
    TO ROLE AIRLINE_US_ANALYST;

GRANT ROLE AIRLINE_US_ANALYST TO USER "shota.hvaramiia";



#Под ролью аналитика выполнили:
USE ROLE AIRLINE_US_ANALYST;

SELECT AIRPORT_COUNTRY_CODE, COUNT(*) AS VISIBLE_ROWS
FROM AIRLINE_DWH.MART.VW_FACT_AIRLINE_TRAVEL_SECURE
GROUP BY AIRPORT_COUNTRY_CODE;
